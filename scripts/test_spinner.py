#!/usr/bin/env python3
"""Offline data and generation checks for the portable spinner kit."""

import json
from html import escape
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import unittest

import build_spinner


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'extras' / 'spinner'


class SpinnerDataTests(unittest.TestCase):
    def test_vocabulary_is_the_checked_187_word_snapshot(self):
        words = json.loads((ASSETS / 'verbs.json').read_text(encoding='utf-8'))
        self.assertEqual(len(words), 187)
        self.assertEqual(len(set(words)), 187)
        self.assertTrue(all(isinstance(word, str) and word for word in words))
        self.assertEqual(words[0], 'Accomplishing')
        self.assertEqual(words[-1], 'Zigzagging')
        self.assertIn("Beboppin'", words)
        self.assertIn('Flambéing', words)
        self.assertIn('Sautéing', words)

    def test_loader_returns_only_the_public_reuse_contract(self):
        assets = build_spinner.load_spinner_assets(ROOT)
        self.assertEqual(set(assets), {'css', 'js', 'data_json'})
        self.assertTrue(all(isinstance(value, str) for value in assets.values()))
        self.assertEqual(json.loads(assets['data_json']),
                         json.loads((ASSETS / 'verbs.json').read_text(encoding='utf-8')))
        self.assertIn('.cc-spinner-glyph::before', assets['css'])
        self.assertIn('[data-spinner-next]', assets['js'])

    def test_loader_protects_inline_json_from_html_termination(self):
        with tempfile.TemporaryDirectory() as directory:
            sandbox = Path(directory)
            shutil.copytree(ASSETS, sandbox / 'extras' / 'spinner')
            words = json.loads((sandbox / 'extras' / 'spinner' / 'verbs.json').read_text(encoding='utf-8'))
            words[0] = '</script><script>bad()</script>'
            (sandbox / 'extras' / 'spinner' / 'verbs.json').write_text(
                json.dumps(words, ensure_ascii=False), encoding='utf-8')
            assets = build_spinner.load_spinner_assets(sandbox)
            self.assertNotIn('</script', assets['data_json'].lower())
            self.assertEqual(json.loads(assets['data_json'])[0], words[0])

    def test_rejects_wrong_count_and_duplicates(self):
        with tempfile.TemporaryDirectory() as directory:
            sandbox = Path(directory)
            shutil.copytree(ASSETS, sandbox / 'extras' / 'spinner')
            vocabulary = sandbox / 'extras' / 'spinner' / 'verbs.json'
            words = json.loads(vocabulary.read_text(encoding='utf-8'))
            vocabulary.write_text(json.dumps(words[:-1]), encoding='utf-8')
            with self.assertRaisesRegex(ValueError, '187'):
                build_spinner.load_spinner_assets(sandbox)
            vocabulary.write_text(json.dumps(words[:-1] + [words[0]]), encoding='utf-8')
            with self.assertRaisesRegex(ValueError, 'duplicates'):
                build_spinner.load_spinner_assets(sandbox)


class SpinnerGenerationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.words = json.loads((ASSETS / 'verbs.json').read_text(encoding='utf-8'))
        cls.page = (ASSETS / 'index.html').read_text(encoding='utf-8')
        cls.txt = (ASSETS / 'spinner-verbs-2.1.322.txt').read_text(encoding='utf-8')

    def test_tracked_generated_files_match_canonical_sources(self):
        rendered_html, rendered_txt = build_spinner.render_spinner(ROOT)
        self.assertEqual(self.page, rendered_html)
        self.assertEqual(self.txt, rendered_txt)
        self.assertTrue(self.page.startswith(
            '<!doctype html>\n<!-- GENERATED by scripts/build_spinner.py'))

    def test_txt_is_exactly_one_word_per_line(self):
        self.assertEqual(self.txt, '\n'.join(self.words) + '\n')
        self.assertEqual(self.txt.splitlines(), self.words)
        self.assertEqual(self.txt.count('\n'), 187)

    def test_standalone_keeps_full_license_and_versioned_provenance(self):
        self.assertIn(escape((ROOT / 'LICENSE').read_text(encoding='utf-8')), self.page)
        self.assertIn('https://registry.npmjs.org/@anthropic-ai/claude-code-darwin-arm64/2.1.322', self.page)

    def test_standalone_has_no_sibling_or_network_dependencies(self):
        self.assertNotRegex(self.page, r'(?i)<(?:script|link|img|iframe)[^>]+(?:src|href)=[\"\'](?:https?:)?//')
        self.assertNotRegex(self.page, r'(?i)@import|url\(\s*[\"\']?(?:https?:)?//')
        self.assertNotRegex(self.page, r'(?i)<link[^>]+stylesheet')
        self.assertEqual(self.page.count('id=\"cc-spinner-data\"'), 1)
        data = self.page.split('<script type=\"application/json\" id=\"cc-spinner-data\">', 1)[1]
        data = data.split('</script>', 1)[0]
        self.assertEqual(json.loads(data), self.words)
        self.assertNotIn('<!-- CC_SPINNER_', self.page)

    def test_full_word_list_and_original_characters_are_readable(self):
        listed = re.findall(r'^\s{8}<li>(.*?)</li>$', self.page, flags=re.MULTILINE)
        self.assertEqual(len(listed), 187)
        self.assertIn('Beboppin&#x27;', listed)
        self.assertIn('Flambéing', listed)
        self.assertIn('Sautéing', listed)

    def test_animation_contract_and_accessible_controls_are_embedded(self):
        for hook in ('data-cc-spinner', 'data-spinner-glyph', 'data-spinner-word',
                     'data-spinner-next', 'data-spinner-pause', 'data-spinner-download'):
            self.assertIn(hook, self.page)
        for frame in ('·', '✢', '✳', '✶', '✻', '✽'):
            self.assertIn(f'content: "{frame}"', self.page)
        self.assertIn('animation: cc-spinner-frames 1.2s step-end infinite', self.page)
        self.assertIn('[data-cc-spinner][data-paused=\"true\"] .cc-spinner-glyph::before', self.page)
        self.assertIn('@media (prefers-reduced-motion: reduce)', self.page)
        self.assertGreaterEqual(self.page.count('min-height: 44px'), 1)
        self.assertIn(':focus-visible', self.page)
        self.assertIn('aria-pressed=\"false\"', self.page)
        self.assertIn('aria-hidden=\"true\"', self.page)

    def test_builder_cli_regenerates_both_artifacts(self):
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            result = subprocess.run(
                [sys.executable, str(ROOT / 'scripts' / 'build_spinner.py')],
                cwd=output, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn('extras/spinner/index.html', result.stdout)
            self.assertEqual((ASSETS / 'index.html').read_text(encoding='utf-8'), self.page)


if __name__ == '__main__':
    unittest.main(verbosity=2)
